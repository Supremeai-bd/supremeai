"""Skill template writer — successful patterns → skill templates (#4054).

বাংলা: successful DecisionPattern থেকে skill template YAML তৈরি করে।
skill templates L1 context-এ inject হয় যাতে next agent শিখতে পারে।
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

from .pattern_miner import DecisionPattern


def write_skill_template(
    pattern: DecisionPattern,
    output_dir: str | Path = "knowledge/skills",
) -> str:
    """Write a skill template YAML from a successful pattern.

    বাংলা: একটি successful pattern থেকে skill template YAML তৈরি করে।
    file name = skill_{task_type}_{decision_type}.yaml

    Returns:
        path to the written YAML file
    """
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    # Sanitize filename
    safe_task = pattern.task_type.replace("/", "_").replace(" ", "_")
    safe_decision = pattern.decision_type.replace("/", "_").replace(" ", "_")
    filename = f"skill_{safe_task}_{safe_decision}.yaml"
    filepath = out / filename

    # Build YAML content
    template = f"""# Skill template — auto-generated by Learning Loop (#4054)
# বাংলা: এই skill template একটি successful pattern থেকে তৈরি। L1 context-এ
# inject হয় যাতে next agent শিখতে পারে।
# Pattern confidence: {pattern.confidence:.2f} ({pattern.count} occurrences)

skill_id: "skill_{safe_task}_{safe_decision}"
task_type: "{pattern.task_type}"
decision_type: "{pattern.decision_type}"
outcome: "{pattern.outcome}"
confidence: {pattern.confidence:.4f}
sample_count: {pattern.count}

# বাংলা: common evidence — এই evidence-গুলো successful decisions-এ দেখা গেছে।
common_evidence:
"""
    for ev in pattern.common_evidence[:10]:
        template += f'  - "{ev}"\n'

    template += """
# বাংলা: sample decision IDs (audit trail — পুরো record DecisionMetadata-এ)
sample_decisions:
"""
    for did in pattern.sample_decision_ids[:5]:
        template += f'  - "{did}"\n'

    template += """
# Inject into L1 context when:
# - task_type matches
# - similarity score > 0.7
# - pattern.confidence >= 0.5
inject_rule: "on_task_assignment_if_similar"
"""

    filepath.write_text(template, encoding="utf-8")
    return str(filepath)


def write_regression_guard(
    pattern: DecisionPattern,
    output_dir: str | Path = "knowledge/regression_guards",
) -> str:
    """Write a regression guard YAML from a failed pattern.

    বাংলা: failed pattern থেকে regression guard তৈরি করে। future agent-এর
    একই ভুল না করে তা নিশ্চিত করে।

    Returns:
        path to the written YAML file
    """
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    safe_task = pattern.task_type.replace("/", "_").replace(" ", "_")
    safe_decision = pattern.decision_type.replace("/", "_").replace(" ", "_")
    filename = f"guard_{safe_task}_{safe_decision}.yaml"
    filepath = out / filename

    template = f"""# Regression guard — auto-generated by Learning Loop (#4054)
# বাংলা: এই guard একটি failed pattern থেকে তৈরি। future agent-এর একই ভুল
# না করে তা নিশ্চিত করে।
# Pattern: {pattern.count} failures with this (task_type, decision_type)

guard_id: "guard_{safe_task}_{safe_decision}"
task_type: "{pattern.task_type}"
decision_type: "{pattern.decision_type}"
failure_count: {pattern.count}
confidence: {pattern.confidence:.4f}

# বাংলা: এই evidence-গুলো failed decisions-এ দেখা গেছে — avoid!
failure_evidence:
"""
    for ev in pattern.common_evidence[:10]:
        template += f'  - "{ev}"\n'

    template += """
# Block rule: if agent considers this decision_type for this task_type,
# check this guard first. If evidence matches → warn/block.
block_rule: "warn_on_match"
"""

    filepath.write_text(template, encoding="utf-8")
    return str(filepath)
